# Day 15 · ASCII 图案三连

# ---------- ① 倒计时 ----------
print("=== 倒计时 ===")
for i in range(5, 0, -1):
    print(i)
print("发射！🚀")

# ---------- ② 七的乘法表 ----------
print("=== 七的乘法表 ===")
for i in range(1, 10):
    print(f"7 × {i} = {7 * i}")

# ---------- ③ 星星金字塔 ----------
print("=== 星星金字塔 ===")
for i in range(1, 6):
    print(" " * (5 - i) + "★" * (2 * i - 1))
